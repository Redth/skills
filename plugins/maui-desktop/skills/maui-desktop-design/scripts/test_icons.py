class PortCheck(TempDir):
    """a shipping app's icons.json, converted, generates what the source app's gen-icons.mjs generated."""

    def setUp(self):
        super().setUp()
        self.root = self.project("port-check")
        self.expected = kit.load(os.path.join(self.root, "expected.json"))["icons"]
        code, out, err = self.icons("build", "--root", self.root)
        self.assertEqual(code, 0, out + err)

    def test_sprite_matches(self):
        sprite = kit.read(os.path.join(self.root, "src/SampleMonitor.Ui/wwwroot/icons/sprite.svg"))
        self.assertEqual(kit.svg_body(sprite), self.expected["sprite"])
        razor = kit.read(os.path.join(self.root, "src/SampleMonitor.Ui/Components/IconSprite.razor"))
        self.assertEqual(kit.svg_body(razor), self.expected["sprite"])

    def test_csharp_tables_match(self):
        cs = kit.read(os.path.join(self.root, "src/SampleMonitor.Core/Shell/Icons.g.cs"))
        for table in ("SfSymbols", "GtkNames", "SvgBodies"):
            self.assertEqual(kit.parse_cs_strings(cs, table), self.expected[table], table)
        self.assertIn('MarkBodies[name]', cs)
        self.assertIn('["app"] = ', cs)

    def test_mark_imageset_matches(self):
        folder = os.path.join(self.root, "src/SampleMonitor.MacOS/Assets.xcassets/AppMark.imageset")
        self.assertEqual(kit.read(os.path.join(folder, "AppMark.svg")).split("\n"), self.expected["markSvg"])
        contents = kit.load(os.path.join(folder, "Contents.json"))
        self.assertEqual(contents["properties"], self.expected["markProperties"])
        self.assertEqual(contents["images"], [{"filename": "AppMark.svg", "idiom": "universal"}])


class Init(TempDir):
    def test_init_from_blueprint_and_layout(self):
        root = os.path.join(self.tmp, "app")
        kit.make_layout(root)
        kit.make_blueprint(root, ["macos", "windows", "web"])
        code, out, err = self.icons("init", "--root", root)
        self.assertEqual(code, 0, out + err)
        data = kit.load(os.path.join(root, "design", "icons.json"))
        self.assertEqual(data["meta"]["name"], "Sample Notes")
        self.assertEqual(data["platforms"], ["macos", "windows", "web"])
        self.assertEqual(data["outputs"]["csharp"], {"path": "src/SampleNotes.Core/Shell/Icons.g.cs",
                                                     "namespace": "SampleNotes.Core.Shell"})
