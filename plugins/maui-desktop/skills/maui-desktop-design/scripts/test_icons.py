class TempDir(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="icons-test-")
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def project(self, name):
        return kit.fixture(name, os.path.join(self.tmp, name))

    def template_project(self, **changes):
        root = os.path.join(self.tmp, "app")
        data = kit.load(os.path.join(kit.TEMPLATES, "icons.json"))
        data["outputs"] = {"csharp": {"path": "src/App.Core/Shell/Icons.g.cs", "namespace": "App.Core.Shell"},
                           "sprite": "src/App.Ui/wwwroot/icons/sprite.svg",
                           "razor": "src/App.Ui/Components/IconSprite.razor"}
        data.update(changes)
        kit.dump(data, os.path.join(root, "design", "icons.json"))
        return root

    def icons(self, *argv):
        return kit.run(icons, list(argv))

    def icons_json(self, *argv):
        return kit.run_json(icons, list(argv))


class Template(TempDir):
    def test_every_icon_maps_on_every_platform(self):
        data = kit.load(os.path.join(kit.TEMPLATES, "icons.json"))
        self.assertIn("$comment", data)
        self.assertIn("best-effort", " ".join(data["$comment"]))
        names = [n for n in data["icons"] if not n.startswith("$")]
        self.assertGreaterEqual(len(names), 25)
        for name in ("add", "remove", "edit", "refresh", "search", "settings", "close", "chevron-left",
                     "chevron-right", "chevron-down", "more", "filter", "sort", "copy", "folder", "file",
                     "open-external", "info", "warning", "error", "success", "play", "stop", "download", "upload",
                     "sidebar-toggle", "trash"):
            self.assertIn(name, names)
        for name in names:
            icon = data["icons"][name]
            self.assertEqual(sorted(icon), ["fluent", "gtk", "sf", "svg"], name)
            self.assertTrue(icon["gtk"].endswith("-symbolic"), name)
            self.assertRegex(icon["fluent"], r"^E[0-9A-F]{3}$", name)
            self.assertRegex(icon["sf"], r"^[a-z0-9.]+$", name)
            ET.fromstring('<svg xmlns="http://www.w3.org/2000/svg">%s</svg>' % icon["svg"])
        self.assertEqual(len(set(data["icons"][n]["fluent"] for n in names)), len(names))

    def test_builds_and_checks_clean(self):
        root = self.template_project()
        code, out, err = self.icons("build", "--root", root)
        self.assertEqual(code, 0, out + err)
        code, out, err = self.icons("build", "--root", root, "--check")
        self.assertEqual(code, 0, out + err)
        cs = kit.read(os.path.join(root, "src/App.Core/Shell/Icons.g.cs"))
        for method in ("SfSymbol(IconRef icon)", "GtkName(IconRef icon)", "SpriteId(IconRef icon)",
                       "Svg(IconRef icon, string stroke)"):
            self.assertIn(method, cs)
        self.assertNotIn("FluentGlyph", cs)  # meta.windows is svg
        self.assertNotIn("MarkSvg", cs)  # no marks
        self.assertEqual(kit.parse_cs_strings(cs, "SfSymbols")["ChevronLeft"], "chevron.left")
        self.assertEqual(kit.parse_cs_strings(cs, "GtkNames")["SidebarToggle"], "sidebar-show-symbolic")
        sprite = kit.read(os.path.join(root, "src/App.Ui/wwwroot/icons/sprite.svg"))
        self.assertTrue(sprite.startswith("<!-- Generated by icons.py from design/icons.json. Do not edit. -->\n"))
        svg = ET.fromstring("\n".join(kit.svg_body(sprite)))
        ids = [s.get("id") for s in svg]
        self.assertIn("i-open-external", ids)
        self.assertEqual(svg.get("stroke-width"), "1.75")
        razor = kit.read(os.path.join(root, "src/App.Ui/Components/IconSprite.razor"))
        self.assertTrue(razor.startswith("@* Generated by icons.py"))
        self.assertEqual(kit.svg_body(razor), kit.svg_body(sprite))

    def test_fluent_glyphs_when_windows_uses_them(self):
        root = self.template_project(meta={"name": "App", "windows": "fluent"})
        code, out, err = self.icons("build", "--root", root)
        self.assertEqual(code, 0, out + err)
        cs = kit.read(os.path.join(root, "src/App.Core/Shell/Icons.g.cs"))
        self.assertIn("public static string FluentGlyph(IconRef icon) => FluentGlyphs[icon];", cs)
        self.assertIn('[IconRef.Add] = "\\uE710",', cs)
        # The sprite is still an output, so svg stays required and SpriteId stays.
        self.assertIn("SpriteId", cs)


class Incomplete(TempDir):
    def test_a_missing_mapping_fails_and_writes_nothing(self):
        root = self.project("icons-incomplete")
        code, report = self.icons_json("build", "--root", root)
        self.assertEqual(code, 1)
        self.assertEqual([(f["id"], f["where"]) for f in report["findings"]], [("icon-incomplete", "/icons/refresh")])
        self.assertIn('"gtk"', report["findings"][0]["message"])
        self.assertIn("linux", report["findings"][0]["message"])
        self.assertFalse(os.path.exists(os.path.join(root, "src")))
        code, out, _ = self.icons("build", "--root", root, "--check")
        self.assertEqual(code, 1)

    def test_dropping_the_platform_drops_the_requirement(self):
        root = self.project("icons-incomplete")
        path = os.path.join(root, "design", "icons.json")
        data = kit.load(path)
        data["platforms"] = ["macos", "windows", "web"]
        kit.dump(data, path)
        code, out, err = self.icons("build", "--root", root)
        self.assertEqual(code, 0, out + err)
        cs = kit.read(os.path.join(root, "src/SampleNotes.Core/Shell/Icons.g.cs"))
        self.assertNotIn("GtkName", cs)
        self.assertIn("SfSymbol", cs)

    def test_only_listed_platforms_get_methods(self):
        root = self.project("icons-incomplete")
        path = os.path.join(root, "design", "icons.json")
        data = kit.load(path)
        data["platforms"] = ["macos"]
        del data["outputs"]["sprite"]
        for icon in data["icons"].values():
            icon.pop("svg")
        kit.dump(data, path)
        code, out, err = self.icons("build", "--root", root)
        self.assertEqual(code, 0, out + err)
        cs = kit.read(os.path.join(root, "src/SampleNotes.Core/Shell/Icons.g.cs"))
        self.assertIn("SfSymbol", cs)
        for absent in ("GtkName", "SpriteId", "Svg(", "SvgBodies"):
            self.assertNotIn(absent, cs)

    def test_fluent_mode_requires_codepoints(self):
        root = self.project("icons-incomplete")
        path = os.path.join(root, "design", "icons.json")
        data = kit.load(path)
        data["meta"]["windows"] = "fluent"
        data["icons"]["refresh"]["gtk"] = "view-refresh-symbolic"
        kit.dump(data, path)
        code, report = self.icons_json("build", "--root", root)
        self.assertEqual(code, 1)
        self.assertEqual(sorted(f["where"] for f in report["findings"]), ["/icons/add", "/icons/close",
                                                                          "/icons/refresh"])
        self.assertIn('"fluent"', report["findings"][0]["message"])


class InvalidInput(TempDir):
    def write(self, root, data):
        kit.dump(data, os.path.join(root, "design", "icons.json"))

    def base(self):
        return {"version": 1, "platforms": ["macos"], "icons": {"add": {"sf": "plus"}}}

    def test_names_are_kebab_case(self):
        root = os.path.join(self.tmp, "app")
        data = self.base()
        data["icons"]["ChevronLeft"] = {"sf": "chevron.left"}
        self.write(root, data)
        code, report = self.icons_json("build", "--root", root)
        self.assertEqual(code, 3)
        self.assertEqual(kit.ids(report), ["icon-name"])
        self.assertIn("chevron-left", report["findings"][0]["message"])

    def test_schema_violation(self):
        root = os.path.join(self.tmp, "app")
        data = self.base()
        data["icons"]["add"]["fluent"] = "plus"
        self.write(root, data)
        code, report = self.icons_json("build", "--root", root)
        self.assertEqual(code, 3)
        self.assertEqual(kit.ids(report), ["schema"])

    def test_broken_svg(self):
        root = os.path.join(self.tmp, "app")
        data = self.base()
        data["platforms"] = ["web"]
        data["icons"]["add"]["svg"] = "<path d='M12 5v14'>"
        self.write(root, data)
        code, report = self.icons_json("build", "--root", root)
        self.assertEqual(code, 1)
        self.assertEqual(kit.ids(report), ["svg-markup"])

    def test_missing_file(self):
        os.makedirs(os.path.join(self.tmp, "app"))
        code, report = self.icons_json("build", "--root", os.path.join(self.tmp, "app"))
        self.assertEqual(code, 3)
        self.assertEqual(kit.ids(report), ["missing-file"])


